-- Credenciales de equipo: permiten que un aparato (por ejemplo un Monitor T/H con WiFi) envíe datos a un módulo
-- sin la sesión de una persona. Cada credencial sirve para un solo módulo y un solo equipo, se guarda solo como
-- huella SHA-256 (el secreto se muestra una vez al crearla) y se puede revocar.
CREATE TABLE credenciales_equipo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modulo TEXT NOT NULL,                 -- clave del módulo (modulos.clave)
    equipo TEXT NOT NULL,                 -- código del equipo dentro del módulo (p. ej. MTH-03)
    huella TEXT NOT NULL UNIQUE,          -- sha256 del secreto, en hexadecimal
    creada_por BIGINT REFERENCES usuarios(id),
    creada_en TEXT NOT NULL,
    ultimo_uso TEXT,
    ultima_ip TEXT,
    revocada_en TEXT
);
CREATE INDEX ix_credenciales_equipo_modulo ON credenciales_equipo (modulo, equipo);
