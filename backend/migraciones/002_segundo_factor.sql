-- Segundo factor de autenticación (TOTP, RFC 6238: Microsoft Authenticator, Google Authenticator, etc.).
-- El secreto se guarda cifrado; los códigos de respaldo, solo como hash.
ALTER TABLE usuarios ADD COLUMN mfa_secreto TEXT;                          -- cifrado con la clave de data/<clave>/mfa.key
ALTER TABLE usuarios ADD COLUMN mfa_activo INTEGER NOT NULL DEFAULT 0;     -- 1 cuando la persona confirmó su app
ALTER TABLE usuarios ADD COLUMN mfa_exigido INTEGER NOT NULL DEFAULT 0;    -- 1 si un administrador lo exige a esta persona
ALTER TABLE usuarios ADD COLUMN mfa_activado_en TEXT;
ALTER TABLE usuarios ADD COLUMN mfa_ultimo_paso BIGINT;                    -- evita reutilizar el mismo código

-- 0 = sesión completa · 1 = falta ingresar el código · 2 = falta configurar la app (primer uso)
ALTER TABLE sesiones ADD COLUMN mfa_pendiente INTEGER NOT NULL DEFAULT 0;
ALTER TABLE sesiones ADD COLUMN mfa_intentos INTEGER NOT NULL DEFAULT 0;

CREATE TABLE mfa_respaldo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    codigo_hash TEXT NOT NULL,
    usado_en TEXT
);
CREATE INDEX ix_mfa_respaldo_usuario ON mfa_respaldo (usuario_id);
